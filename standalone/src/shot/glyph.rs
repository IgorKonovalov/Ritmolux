//! Minimal 5x7 bitmap font for contact-sheet labels (A-Z 0-9 space - .).
//!
//! The table is here and the rasterizer is not: drawing needs an `image` canvas,
//! which stays a dev-dependency (ADR-0011). What is worth pinning is that the
//! table is well-formed — a glyph with a bit outside the low 5 columns bleeds
//! into its neighbour, and an unmapped character must be blank, not garbage.

/// Advance per character in unscaled pixels: 5 columns plus a 1px gutter.
pub const GLYPH_ADVANCE: u32 = 6;
/// Glyph height in unscaled pixels.
pub const GLYPH_ROWS: usize = 7;
/// Glyph width in unscaled pixels.
pub const GLYPH_COLS: u32 = 5;

/// 7 rows (top->bottom); each byte's low 5 bits are the columns (bit4 = left).
/// Unmapped characters (including space) render blank.
pub fn glyph_for(ch: char) -> [u8; GLYPH_ROWS] {
    match ch {
        'A' => [0x0E, 0x11, 0x11, 0x1F, 0x11, 0x11, 0x11],
        'B' => [0x1E, 0x11, 0x11, 0x1E, 0x11, 0x11, 0x1E],
        'C' => [0x0E, 0x11, 0x10, 0x10, 0x10, 0x11, 0x0E],
        'D' => [0x1E, 0x11, 0x11, 0x11, 0x11, 0x11, 0x1E],
        'E' => [0x1F, 0x10, 0x10, 0x1E, 0x10, 0x10, 0x1F],
        'F' => [0x1F, 0x10, 0x10, 0x1E, 0x10, 0x10, 0x10],
        'G' => [0x0E, 0x11, 0x10, 0x17, 0x11, 0x11, 0x0F],
        'H' => [0x11, 0x11, 0x11, 0x1F, 0x11, 0x11, 0x11],
        'I' => [0x0E, 0x04, 0x04, 0x04, 0x04, 0x04, 0x0E],
        'J' => [0x07, 0x02, 0x02, 0x02, 0x02, 0x12, 0x0C],
        'K' => [0x11, 0x12, 0x14, 0x18, 0x14, 0x12, 0x11],
        'L' => [0x10, 0x10, 0x10, 0x10, 0x10, 0x10, 0x1F],
        'M' => [0x11, 0x1B, 0x15, 0x15, 0x11, 0x11, 0x11],
        'N' => [0x11, 0x11, 0x19, 0x15, 0x13, 0x11, 0x11],
        'O' => [0x0E, 0x11, 0x11, 0x11, 0x11, 0x11, 0x0E],
        'P' => [0x1E, 0x11, 0x11, 0x1E, 0x10, 0x10, 0x10],
        'Q' => [0x0E, 0x11, 0x11, 0x11, 0x15, 0x12, 0x0D],
        'R' => [0x1E, 0x11, 0x11, 0x1E, 0x14, 0x12, 0x11],
        'S' => [0x0F, 0x10, 0x10, 0x0E, 0x01, 0x01, 0x1E],
        'T' => [0x1F, 0x04, 0x04, 0x04, 0x04, 0x04, 0x04],
        'U' => [0x11, 0x11, 0x11, 0x11, 0x11, 0x11, 0x0E],
        'V' => [0x11, 0x11, 0x11, 0x11, 0x11, 0x0A, 0x04],
        'W' => [0x11, 0x11, 0x11, 0x15, 0x15, 0x15, 0x0A],
        'X' => [0x11, 0x11, 0x0A, 0x04, 0x0A, 0x11, 0x11],
        'Y' => [0x11, 0x11, 0x0A, 0x04, 0x04, 0x04, 0x04],
        'Z' => [0x1F, 0x01, 0x02, 0x04, 0x08, 0x10, 0x1F],
        '0' => [0x0E, 0x11, 0x13, 0x15, 0x19, 0x11, 0x0E],
        '1' => [0x04, 0x0C, 0x04, 0x04, 0x04, 0x04, 0x0E],
        '2' => [0x0E, 0x11, 0x01, 0x06, 0x08, 0x10, 0x1F],
        '3' => [0x1F, 0x02, 0x04, 0x02, 0x01, 0x11, 0x0E],
        '4' => [0x02, 0x06, 0x0A, 0x12, 0x1F, 0x02, 0x02],
        '5' => [0x1F, 0x10, 0x1E, 0x01, 0x01, 0x11, 0x0E],
        '6' => [0x06, 0x08, 0x10, 0x1E, 0x11, 0x11, 0x0E],
        '7' => [0x1F, 0x01, 0x02, 0x04, 0x08, 0x08, 0x08],
        '8' => [0x0E, 0x11, 0x11, 0x0E, 0x11, 0x11, 0x0E],
        '9' => [0x0E, 0x11, 0x11, 0x0F, 0x01, 0x02, 0x0C],
        '-' => [0x00, 0x00, 0x00, 0x1F, 0x00, 0x00, 0x00],
        '.' => [0x00, 0x00, 0x00, 0x00, 0x00, 0x06, 0x06],
        _ => [0x00; GLYPH_ROWS], // space + anything unmapped
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    /// Every mapped glyph must fit the 5 columns it is allotted. A bit at 0x20 or
    /// above would draw into the next character's cell.
    #[test]
    fn every_glyph_fits_five_columns() {
        for ch in ('A'..='Z').chain('0'..='9').chain(['-', '.']) {
            let g = glyph_for(ch);
            for (row, bits) in g.iter().enumerate() {
                assert!(
                    *bits < (1 << GLYPH_COLS),
                    "`{ch}` row {row} has a bit outside the 5-column cell: {bits:#04x}"
                );
            }
            assert!(
                g.iter().any(|b| *b != 0),
                "`{ch}` is mapped but draws nothing"
            );
        }
    }

    /// Unmapped input is blank rather than garbage, and the table is
    /// uppercase-only — the caller uppercases, so a lowercase lookup is blank.
    #[test]
    fn unmapped_characters_are_blank() {
        assert_eq!(glyph_for(' '), [0; GLYPH_ROWS]);
        assert_eq!(glyph_for('%'), [0; GLYPH_ROWS]);
        assert_eq!(glyph_for('_'), [0; GLYPH_ROWS]);
        assert_eq!(glyph_for('\u{e9}'), [0; GLYPH_ROWS], "non-ASCII is blank");
        assert_eq!(glyph_for('a'), [0; GLYPH_ROWS], "lowercase is not mapped");
        assert_eq!(glyph_for('A'), glyph_for('a'.to_ascii_uppercase()));
    }

    /// A spot-check that the bit convention is bit4 = leftmost column: `L` is a
    /// left stem with a full bottom bar, so every row but the last is exactly the
    /// leftmost pixel.
    #[test]
    fn the_bit_convention_is_msb_left() {
        let l = glyph_for('L');
        for bits in &l[..GLYPH_ROWS - 1] {
            assert_eq!(*bits, 0x10, "left column only");
        }
        assert_eq!(l[GLYPH_ROWS - 1], 0x1F, "full bottom bar");
        // `1` is centred: column 2 of 0..5 is bit 2.
        assert_eq!(glyph_for('1')[0], 0x04);
        // The advance leaves exactly one blank column between cells.
        assert_eq!(GLYPH_ADVANCE, GLYPH_COLS + 1);
    }
}
