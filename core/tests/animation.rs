//! Animation liveness (Plan 0013 Phase 3, HARD). A scene must change over time
//! independent of audio: hold the audio frame constant and compare frame N with
//! frame N+k. A frozen scene (e.g. `time` unbound, or a stuck clock) reads as
//! near-zero and fails. Silent audio is used deliberately — the motion under
//! test is the shared scene clock, not an audio edge.
//!
//! **Plan 0077 Phase 1 / ADR-0091: motion is scored against the figure's own
//! footprint, not the whole frame.** The original statistic was
//! `metrics::frame_diff`, a mean over every pixel, which dilutes a sparse
//! figure's motion into the empty frame around it — it scores *occupancy*, and
//! Plan 0067 Phase 1d measured occupancy to be scale-invariant (the ladder at
//! the bottom of this file), so no render size fixes it. The gate now uses
//! `metrics::footprint_diff`: the same mean, taken over the union of lit
//! pixels in the two frames only. The capture roster has its `bg_*` bindings
//! stripped ([`without_backdrop`]) for the same reason sanity.rs strips them
//! (ADR-0067): a shipped backdrop's dim gradient sits above the lit threshold
//! in sRGB, and measured *with* backdrops the sparse probe's footprint read as
//! 65 % of the frame — the dilution this change exists to remove, back again
//! by another door.
//!
//! **Plan 0123 Phase 1 / ADR-0136: the gate asks its question in both
//! readings.** Autonomous motion and liveliness were the same property for
//! every world the library held when this file was written, and they stopped
//! being the same one for a poster built to sit still and do its moving in
//! response to the music. So a preset passes on **either** reading: the silent
//! motion above, or a silent-versus-driven differential — the same
//! `footprint_diff`, over the silent capture and one taken against
//! [`AnalysisFrame::fully_driven`] at the same frame count. A preset frozen in
//! **both** still fails, which is the only sense in which this gate has ever
//! meant frozen. Each preset's test prints which branch carried its pass, so
//! "still in silence" is a visible label on every preset rather than an
//! invisible consequence of an `||`.
//!
//! **The sweep is one test per preset** (ADR-0157), generated by `core/build.rs`
//! from the same `presets/*.toml` glob that emits the embedded set and
//! `include!`d below [`animates_over_time`]. nextest parallelizes across tests
//! and never inside one, so the roster written as a single `#[test]` ran on one
//! core with the rest of the box idle.
//!
//! Both branches score **this gate's own statistic**. The driven reading is not
//! `reactivity.rs`'s: that gate measures `frame_diff` — a whole-frame mean — on
//! real PCM through the real analyzer, and it stays the only gate that does.
//! Disjoining two floors on two statistics in two units would be the ADR-0071 /
//! ADR-0074 error with an `||` in front of it.
//!
//! Software adapter so it holds on any CI GPU.
//!
//! The resolution ladder at the bottom of this file (Plan 0067 Phase 1d) is a
//! **measurement, not a gate** — it is `#[ignore]`d, records why [`SIZE`] did
//! not move, and stays pinned to the whole-frame statistic it measured.

use rlx_core::dsp::AnalysisFrame;
use rlx_core::preset::{Preset, SystemKind, default_presets};
use rlx_core::render::{
    Renderer,
    metrics::{footprint_diff, frame_diff},
};

