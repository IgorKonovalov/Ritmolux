/// Capture size for the gate.
///
/// **Measured against the two designs it penalizes at Plan 0067 Phase 1d and
/// deliberately left alone** — see [`the_resolution_ladder_against_the_two_designs_it_penalizes`]
/// for the ladder and the numbers.
const SIZE: u32 = 96;
/// The earlier and later capture points (frames). The ~0.4 s gap at the fixed
/// 60 fps `SCENE_DT` is ample for any live scene to move visibly.
const FRAME_A: u32 = 24;
const FRAME_B: u32 = 48;
/// Minimum motion between the two frames, in `metrics::footprint_diff`'s
/// mean-abs-over-the-lit-footprint units (0..1). Catches a *frozen* scene, not
/// a subtly-animated one.
///
/// **Re-derived against the footprint statistic at Plan 0077 Phase 1
/// (ADR-0091), from the same measurement the sweep above prints on every run.**
/// The whole-frame floor this replaces was also 0.01; the number surviving is
/// a coincidence of the derivation, not a constant carried over. The derivation,
/// per ADR-0071:
///
/// - **The population is the presets that pass on THIS branch**, and naming it
///   is load-bearing. A preset carried by the driven branch is still by design
///   (ADR-0136) and reads near zero here on purpose, so folding it in would
///   derive this floor from the frames the branch exists to let through.
///   Re-measured 2026-09-01, DX12 software adapter, backdrops suppressed, 81
///   shipped presets: **74 pass on this branch and their minimum is 0.0155**
///   (`Nocturne`), so the floor sits 1.55x under it. The seven the driven
///   branch carries run from `Heart Mono`'s **0.0000** up.
/// - **The floor is `0.01` because half of `0.0205` (`Banded Mandala`, measured
///   2026-08-12 on the same adapter) rounds there**, on the per-system-floor
///   ceremony `sanity.rs` uses. Half of the branch minimum above is `0.0078`,
///   so the number in force is the *stricter* of the two derivations. It stays
///   put: above what the ceremony gives on today's population, and still under
///   every preset the branch admits.
/// - **Do not re-derive by reading the top of the printed sweep.** The sweep
///   prints one line per preset with no branch filter, and its lowest rows are
///   the driven-branch worlds — the minimum off it is `0.0000` and half of
///   that admits everything, including the flicker the noise ceiling below
///   exists to exclude. Filter to the branch, then take the minimum.
/// - The noise ceiling sits **below** it: with the mask floored at
///   [`MIN_FOOTPRINT_FRAC`], the worst-case stray event ADR-0091 names (one
///   pixel swinging full-scale on all three channels in an otherwise empty
///   frame) reads `1/139 = 0.0072` — under this floor with 1.4x margin, so a
///   flicker cannot clear a gate that the branch's own minimum clears by 1.55x.
/// - The non-vacuity pair brackets it: the rejected fifth-density Squall draft
///   reads **0.1049** (10.5x the floor, against 0.0057 under the whole-frame
///   statistic that priced it out), and the static control reads **0.0000** —
///   a zero numerator, which no normalization can rescue (ADR-0091's safety
///   argument). The pair is pinned as a standing test below.
const ANIM_FLOOR: f32 = 0.01;
/// Minimum silent-versus-driven differential, in the same `footprint_diff`
/// units as [`ANIM_FLOOR`] and over the same mask — the floor the **driven**
/// branch clears (ADR-0136). A preset under both floors is frozen and fails.
///
/// **Derived from the sweep this file prints, on the convention
/// [`ANIM_FLOOR`]'s own derivation uses**, per ADR-0071:
///
/// - **The population is the presets that pass on THIS branch**, which is a
///   narrower set than the library and reads exactly like the library.
///   [`Motion::branch`] tests the silent reading first and returns, so a preset
///   that moves on its own clock is never measured against this floor at all:
///   its driven reading is a number the gate does not consult, and deriving
///   from it would fix a floor off frames it does not gate. Re-measured
///   2026-09-01, DX12 software adapter, backdrops suppressed, 81 shipped
///   presets: **seven pass on this branch and their minimum is 0.0577**
///   (`Stipple`), so the floor sits 3.4x under it. Across all 81 the median
///   driven reading is 0.19 and the maximum 0.68.
/// - **The floor is `0.017` because half of `0.0345` (`Valentine`, measured
///   2026-08-27 over 53 presets) rounds down there** — but `Valentine` passes
///   on the *silent* branch, so that derivation read the whole library rather
///   than this branch's population. The library's lowest driven reading today
///   is `Thomas on Red`'s **0.0320**, and it too is a silent-branch preset. The
///   number stands: it is well under this branch's real minimum, and moving it
///   is not what naming the population is for.
/// - The noise ceiling sits **below** it, and it is literally the same ceiling.
///   This statistic is `footprint_diff` over a mask floored at
///   [`MIN_FOOTPRINT_FRAC`], so ADR-0091's worst-case stray event — one pixel
///   swinging full-scale on all three channels in an otherwise empty frame —
///   reads `1/139 = 0.0072` here too, under this floor with 2.4x margin.
/// - The non-vacuity pair brackets it, and its low end is the sharper half.
///   `probe_collage_mono_calm` — the still-by-design world this branch exists
///   for — reads **0.0621**, 3.7x the floor. `rosette_spin_only` reads
///   **0.0000**: it turns steadily on its own clock and binds no band, so a
///   figure that moves but not *with the music* has a zero numerator here,
///   exactly as the static control does on both readings. Both are pinned as
///   standing tests below.
const DRIVEN_FLOOR: f32 = 0.017;

/// A pixel counts as lit (in the footprint) if any RGB channel differs from
/// [`BLACK`] by more than this — the sanity suite's convention, same value,
/// same reason: shrugs off near-black dithering.
const EPS: u8 = 10;
/// What the footprint is measured against. Not a sampled pixel: the backdrop is
/// suppressed for this capture ([`without_backdrop`]), so every lit pixel is
/// light the **scene** put there.
///
/// **Audited at Plan 0116 Phase 3 and deliberately left constant.** `sanity.rs`
/// now derives its reference per capture (ADR-0126) because a scene that paints
/// its own ground reads `coverage` exactly `1.0` against black. This measure
/// has no single frame to derive from — `footprint_diff` masks over the
/// **union** of two captures, so a per-frame ground would give the mask two
/// references and make the union ill-defined. It is also a *difference*: a
/// scene whose ground is a constant off-white contributes nothing to the
/// numerator whatever the reference calls it, which is the property
/// [`ANIM_FLOOR`] is derived against.
const BLACK: [u8; 4] = [0, 0, 0, 255];
/// Lower bound on `footprint_diff`'s denominator, as a fraction of the frame —
/// the guard ADR-0091 requires against a tiny mask amplifying noise. `0.015` of
/// a 96x96 frame floors the mask at **139 pixels**, which caps the one-pixel
/// full-swing flicker at `0.0072`, under [`ANIM_FLOOR`] (the derivation there).
/// The cost side: a figure lighting less than 1.5 % of the frame has its score
/// scaled down by `mask/139`. The sparsest *silent* footprint in the shipped
/// library is ~7 % of the frame (`Halo` — read any preset's mask fraction off
/// the sweep as `whole-frame / footprint`), 4.5x this bound, so no shipped
/// content is diluted. A future look that sits near this bound is being told
/// it is near-invisible at 96x96 — surface that at the coverage gate rather
/// than tuning this epsilon to pass (ADR-0091's stated risk).
const MIN_FOOTPRINT_FRAC: f32 = 0.015;

/// The prefix every background-stage parameter carries (see sanity.rs, which
/// established the convention and the guard below).
const BG_PREFIX: &str = "bg_";

/// Strip the backdrop bindings so the footprint is the **scene's** lit pixels
/// (ADR-0067's lesson, re-learned here by measurement: a shipped `bg_bright` of
/// 0.016 stores as ~34/255 in sRGB — over [`EPS`] — so with the backdrop on,
/// the "footprint" of a sparse emitter read as 65 % of the frame and the
/// statistic went straight back to diluting by emptiness). The background stage
/// defaults to a black clear, so this is removing bindings, not adding a path.
///
/// Backdrop drift (a slow `bg_hue` sweep) deliberately does **not**
/// count as animation. The gate's question is whether the *scene*
/// moves; a picture whose only life is its vignette breathing is
/// exactly what it should convict.
fn without_backdrop(mut preset: Preset) -> Preset {
    preset.params.retain(|b| !b.name.starts_with(BG_PREFIX));
    preset
}

/// The shipped library, backdrops suppressed, plus `(name, system)` per preset.
/// Panics if the transform matched nothing — the same guard-on-the-guard as
/// sanity.rs: a rename off `bg_` would silently put the backdrop back into the
/// footprint.
fn animation_roster() -> (Vec<Preset>, Vec<(String, SystemKind)>) {
    let mut stripped = 0usize;
    let presets: Vec<Preset> = default_presets()
        .into_iter()
        .map(|p| {
            let before = p.params.len();
            let p = without_backdrop(p);
            stripped += before - p.params.len();
            p
        })
        .collect();
    assert!(
        stripped > 0,
        "no `{BG_PREFIX}*` binding was found in any of the {} shipped presets — the \
         backdrop suppression the footprint statistic rests on has become a no-op",
        presets.len()
    );
    let meta = presets.iter().map(|p| (p.name.clone(), p.system)).collect();
    (presets, meta)
}

fn system_name(system: SystemKind) -> &'static str {
    match system {
        SystemKind::FragmentField => "fragment_field",
        SystemKind::Swarm => "swarm",
        SystemKind::ParametricCurve => "parametric_curve",
        SystemKind::LSystem => "lsystem",
        SystemKind::StarPattern => "star_pattern",
        SystemKind::ReactionDiffusion => "reaction_diffusion",
        SystemKind::Attractor => "attractor",
        SystemKind::Spectrum => "spectrum",
        SystemKind::Emitter => "emitter",
        SystemKind::ShapeField => "shape_field",
        SystemKind::WarpMesh => "warp_mesh",
        SystemKind::ShapeCollage => "shape_collage",
    }
}

/// One preset's three readings (ADR-0136).
#[derive(Clone, Copy)]
struct Motion {
    /// `footprint_diff` between frames [`FRAME_A`] and [`FRAME_B`] at silence:
    /// the scene's own clock, which [`ANIM_FLOOR`] gates.
    silent: f32,
    /// `footprint_diff` between the silent and the fully-driven capture, **both
    /// at [`FRAME_B`]**: the picture the music alone makes, which
    /// [`DRIVEN_FLOOR`] gates.
    driven: f32,
    /// The whole-frame mean over the silent pair — printed, never gated, and
    /// what the ladder at the bottom of this file stays pinned to.
    whole: f32,
}

impl Motion {
    /// Which branch carries this preset's pass, or `None` when it is frozen in
    /// both readings — the one verdict this gate fails on.
    ///
    /// Silent is tested first so the label names the *stronger* property when a
    /// preset has both: a world that moves on its own is reported as one even
    /// when the music moves it too. That ordering is what makes the printed
    /// `driven` roster mean "still in silence" rather than "happened to be
    /// checked second".
    fn branch(self) -> Option<&'static str> {
        if self.silent >= ANIM_FLOOR {
            Some("silent")
        } else if self.driven >= DRIVEN_FLOOR {
            Some("driven")
        } else {
            None
        }
    }
}

/// Every reading over one preset: two captures at silence, [`FRAME_A`] and
/// [`FRAME_B`] apart, plus one at [`FRAME_B`] against
/// [`AnalysisFrame::fully_driven`].
///
/// Three captures rather than four: the driven differential shares the silent
/// [`FRAME_B`] capture with the autonomous one, so the second reading costs one
/// capture per preset and both are anchored at the same point in the scene's
/// own clock.
fn motions(renderer: &mut Renderer, name: &str) -> Motion {
    let silent_audio = AnalysisFrame::default();
    let early = renderer
        .capture_preset(name, &silent_audio, FRAME_A)
        .expect("capture early frame");
    let late = renderer
        .capture_preset(name, &silent_audio, FRAME_B)
        .expect("capture late frame");
    let driven = renderer
        .capture_preset(name, &AnalysisFrame::fully_driven(), FRAME_B)
        .expect("capture driven frame");
    Motion {
        silent: footprint_diff(&early, &late, BLACK, EPS, MIN_FOOTPRINT_FRAC),
        driven: footprint_diff(&late, &driven, BLACK, EPS, MIN_FOOTPRINT_FRAC),
        whole: frame_diff(&early, &late),
    }
}

/// One preset's animation gate, as each generated `#[test]` calls it.
///
/// The whole roster is still built and handed to the renderer, because
/// [`animation_roster`]'s guard is a claim about the *library* — some preset
/// must carry a `bg_*` binding — and does not decompose to one preset. That
/// costs a TOML parse; what costs is the three captures, and those are scoped
/// to `name`.
///
/// The branch label ADR-0136 asks to be visible is printed here per preset
/// rather than collected into one list at the end of a sweep: with a test per
/// preset there is no end of a sweep to collect at, and nextest attributes the
/// line to the preset's own test either way.
fn animates_over_time(name: &str) {
    let Some(mut renderer) = common::headless(SIZE, SIZE) else {
        return;
    };

    let (presets, meta) = animation_roster();
    let system = meta
        .iter()
        .find(|(n, _)| n == name)
        .map(|(_, s)| *s)
        .unwrap_or_else(|| {
            panic!(
                "`{name}` is not in the shipped roster. The generated tests come from the same \
                 `presets/*.toml` glob as the embedded set, so this means a preset's `name` key \
                 parses to something other than what the build script scanned out of its preamble"
            )
        });
    renderer.set_presets(presets);

    let m = motions(&mut renderer, name);
    let branch = m.branch();
    println!(
        "[{}] {name:<14} frames {FRAME_A}/{FRAME_B}: silent {:.4}  driven {:.4}  -> {:<6} (whole-frame {:.4})",
        system_name(system),
        m.silent,
        m.driven,
        branch.unwrap_or("FROZEN"),
        m.whole,
    );

    assert!(
        branch.is_some(),
        "{name} animates on neither reading: silent {:.4} is under the {ANIM_FLOOR} floor and \
         driven {:.4} is under the {DRIVEN_FLOOR} floor",
        m.silent,
        m.driven,
    );
}

// One `#[test]` per shipped preset, each calling `animates_over_time` with the
// preset's `name`. Generated into OUT_DIR by `core/build.rs`, so a new `.toml`
// gets a test by existing. The test is named for the preset's FILENAME, which
// is unique and already ident-shaped, so a failure names the preset and
// `-E 'test(animation_<stem>)'` selects exactly one.
include!(concat!(env!("OUT_DIR"), "/animation_tests.rs"));

/// **The two pinned non-vacuity probes of ADR-0091, as a standing gate** (Plan
/// 0077 Phase 1): the rejected fifth-density Squall draft — the sparse-but-moving
/// design the whole-frame statistic diluted to 0.0051 — must **pass** the
/// footprint statistic, and Phase 1d's static control must keep **failing** it.
/// Together they pin the change to exactly the class ADR-0091 claims it moves:
/// if the draft ever fails, the statistic has regressed to scoring occupancy; if
/// the control ever passes, the floor has stopped gating anything.
///
/// **The control is checked on both branches** (ADR-0136). It does not move in
/// silence and it does not move under full drive — nothing in it reads `time` or
/// any band — and that pair is what frozen has always meant here. A disjunction
/// weakens a gate exactly as far as one branch and no further, so a control that
/// had to fail only one of them would stop pinning the other.
///
/// **`rosette_spin_only` is the third probe, and it is what makes the control's
/// driven zero mean anything.** A figure frozen in both readings satisfies a
/// driven statistic that measures nothing at all exactly as well as it satisfies
/// a working one. This probe turns steadily on its own clock and binds no band,
/// so it is the one frame in this file that separates *responds to the music*
/// from *moves*: its silent reading must stay above the floor (or its driven
/// zero is vacuous) and its driven reading must stay at zero.
///
/// Runs at [`SIZE`] only — the ladder below already measured that resolution
/// does not move either statistic.
#[test]
fn the_footprint_statistic_separates_the_rejected_draft_from_the_static_control() {
    let Some(mut renderer) = common::headless(SIZE, SIZE) else {
        return;
    };
    let probes = probes();
    let presets: Vec<Preset> = probes
        .iter()
        .map(|(label, _, src)| {
            let p = Preset::from_toml_str(src)
                .unwrap_or_else(|e| panic!("probe `{label}` parses: {e}"));
            without_backdrop(p)
        })
        .collect();
    let names: Vec<String> = presets.iter().map(|p| p.name.clone()).collect();
    renderer.set_presets(presets);

    let mut sparse = None;
    let mut frozen = None;
    let mut rosette = None;
    for ((label, note, _), name) in probes.iter().zip(names.iter()) {
        let m = motions(&mut renderer, name);
        println!(
            "{label:<20} silent {:.4}  driven {:.4} (whole-frame {:.4})   {note}",
            m.silent, m.driven, m.whole,
        );
        match *label {
            "squall_sparse" => sparse = Some(m),
            "star_frozen" => frozen = Some(m),
            "rosette_spin_only" => rosette = Some(m),
            _ => {}
        }
    }
    let (Some(sparse), Some(frozen), Some(rosette)) = (sparse, frozen, rosette) else {
        panic!("the probe roster no longer carries the three pinned probes");
    };
    assert!(
        sparse.silent >= ANIM_FLOOR,
        "THE REJECTED DRAFT fails the footprint statistic ({:.4} < {ANIM_FLOOR}) — \
         it has regressed to scoring occupancy (ADR-0091)",
        sparse.silent,
    );
    assert!(
        frozen.silent < ANIM_FLOOR,
        "THE STATIC CONTROL passes the SILENT branch ({:.4} >= {ANIM_FLOOR}) — \
         the floor no longer gates anything",
        frozen.silent,
    );
    assert!(
        frozen.driven < DRIVEN_FLOOR,
        "THE STATIC CONTROL passes the DRIVEN branch ({:.4} >= {DRIVEN_FLOOR}) — a \
         figure with no audio binding is moving under full drive, so the driven \
         floor is measuring something other than the music (ADR-0136)",
        frozen.driven,
    );
    // The static control's driven zero above is consistent with a driven
    // statistic that measures nothing at all: a figure frozen in both
    // readings satisfies it exactly as well. This probe is what separates
    // the two. It turns steadily on its own clock and binds no band, so it
    // moves in silence and must still read zero on the differential.
    assert!(
        rosette.silent >= ANIM_FLOOR,
        "THE SYMMETRIC CASE stopped moving in silence ({:.4} < {ANIM_FLOOR}) \
         - its driven zero below is then vacuous, and this file no longer \
         holds the driven reading to responding to the music rather than \
         to motion",
        rosette.silent,
    );
    assert!(
        rosette.driven < DRIVEN_FLOOR,
        "THE SYMMETRIC CASE passes the DRIVEN branch ({:.4} >= {DRIVEN_FLOOR}) \
         - it binds no band, so autonomous motion has leaked into the \
         driven differential and the branch is scoring rotation as \
         reactivity (ADR-0136)",
        rosette.driven,
    );
}

/// **The world the driven branch exists for, measured before anything depends on
/// it** (Plan 0123 Phase 1): `collage_mono` at the `pan_x`/`pan_y` rates its
/// composition asked for must fail the silent branch and pass the driven one.
///
/// The shipped file is read through [`include_str!`] and its two rate lines are
/// rewritten here, so this measures the preset the content lane wants **without
/// editing it**: the gate is shown to carry the case before the preset depends
/// on it doing so. If the rates in the file come down to these, this probe
/// measures the shipped preset and still asserts the same property.
///
/// The assertion on the *silent* branch is the load-bearing half. Without it a
/// preset that started animating on its own would pass this test while the
/// driven branch went unexercised, and the case ADR-0136 added it for would have
/// quietly stopped being covered.
#[test]
fn the_driven_branch_carries_the_world_that_is_still_by_design() {
    let Some(mut renderer) = common::headless(SIZE, SIZE) else {
        return;
    };
    let src = with_param(
        &with_param(
            &with_param(COLLAGE_MONO_SRC, "pan_x", "0.06 * sin(time * 0.07)"),
            "pan_y",
            "0.04 * sin(time * 0.09 + 1.1)",
        ),
        "name",
        "probe_collage_mono_calm",
    );
    let preset = without_backdrop(
        Preset::from_toml_str(&src).unwrap_or_else(|e| panic!("the calm probe parses: {e}")),
    );
    let name = preset.name.clone();
    renderer.set_presets(vec![preset]);

    let m = motions(&mut renderer, &name);
    println!(
        "{name:<24} silent {:.4}  driven {:.4}  -> {:<6} (whole-frame {:.4})",
        m.silent,
        m.driven,
        m.branch().unwrap_or("FROZEN"),
        m.whole,
    );
    assert!(
        m.silent < ANIM_FLOOR,
        "THE CALM PROBE clears the silent floor ({:.4} >= {ANIM_FLOOR}) — it is not \
         the still-by-design case the driven branch was added for, so this test \
         has stopped exercising that branch",
        m.silent,
    );
    assert!(
        m.driven >= DRIVEN_FLOOR,
        "THE CALM PROBE fails the driven floor ({:.4} < {DRIVEN_FLOOR}) — the \
         branch ADR-0136 added does not carry the preset it was added for",
        m.driven,
    );
}

